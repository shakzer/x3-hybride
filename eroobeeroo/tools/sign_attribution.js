'use strict';
/**
 * sign_attribution.js - signs the credit in shared/attribution.js with the author's private key, so the apps can
 * tell an official build from an altered one.
 *
 *   node tools/sign_attribution.js
 *
 * The private key lives in secret/attribution_key.pem (git-ignored, NEVER pushed): back it up somewhere safe.
 * If it is missing, this makes a new keypair - which changes the fingerprint, so publish the new one. It writes
 * shared/attribution_sig.js (committed): the PUBLIC key, the signature, and the key's fingerprint.
 *
 * Runs on the host's Node (keypair generation needs Node >= 12); the apps only verify, which Node 8 can do.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SECRET = path.join(ROOT, 'secret');
const KEY = path.join(SECRET, 'attribution_key.pem');
const OUT = path.join(ROOT, 'shared', 'attribution_sig.js');

// the signed bytes must match shared/attribution.js canonical() exactly
const INFO = require(path.join(ROOT, 'shared', 'attribution')).INFO;
const FIELDS = ['app', 'author', 'repo', 'url', 'notice'];
const canonical = FIELDS.map((k) => INFO[k]).join('\n');

function loadOrMakeKey() {
    if (fs.existsSync(KEY)) return fs.readFileSync(KEY, 'utf8');
    fs.mkdirSync(SECRET, { recursive: true });
    console.log('No private key: making a new one at ' + KEY + ' (back it up; its fingerprint is new).');
    const { privateKey } = crypto.generateKeyPairSync('rsa', { modulusLength: 3072 });
    const pem = privateKey.export({ type: 'pkcs8', format: 'pem' });
    fs.writeFileSync(KEY, pem, { mode: 0o600 });
    return pem;
}

const privPem = loadOrMakeKey();
const priv = crypto.createPrivateKey(privPem);
const pubPem = crypto.createPublicKey(priv).export({ type: 'spki', format: 'pem' });

const signer = crypto.createSign('RSA-SHA256');
signer.update(canonical, 'utf8');
signer.end();
const signature = signer.sign(priv).toString('base64');

// a short, human-checkable fingerprint of the public key
const fp = crypto.createHash('sha256').update(pubPem).digest('hex').slice(0, 16).replace(/(.{4})(?=.)/g, '$1-');

const body = "'use strict';\n"
    + '/* Generated by tools/sign_attribution.js - do not edit by hand. The author\'s public key, the signature over\n'
    + ' * the credit in attribution.js, and the key fingerprint. The private key is in secret/ and is never pushed. */\n'
    + 'module.exports = ' + JSON.stringify({ pub: pubPem, sig: signature, fp }, null, 2) + ';\n';
fs.writeFileSync(OUT, body);

console.log('Signed the credit. Fingerprint: ' + fp);
console.log('Wrote ' + path.relative(ROOT, OUT) + ' (commit it). Keep ' + path.relative(ROOT, KEY) + ' private.');

// a sanity check: verify with the public key, exactly as the apps do
const v = crypto.createVerify('RSA-SHA256');
v.update(canonical, 'utf8');
v.end();
if (!v.verify(pubPem, Buffer.from(signature, 'base64'))) { console.error('self-check failed'); process.exit(1); }
console.log('Self-check passed.');
